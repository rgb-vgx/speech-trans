#!/usr/bin/env python
"""Install the Chrome native-messaging host for the SpeechTrans extension.

    cd server && uv run python scripts/install_native_host.py
    uv run python scripts/install_native_host.py --uninstall

Writes:
  * server/scripts/native_host.sh            (wrapper that starts this venv)
  * ~/.config/google-chrome/NativeMessagingHosts/com.speechtrans.bridge.json
  * ~/.config/chromium/NativeMessagingHosts/com.speechtrans.bridge.json

The extension ID is derived from the ``key`` field in extension/manifest.json, so
it is stable across machines and is used in ``allowed_origins``.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import shutil
import stat
import sys
from pathlib import Path

HOST_NAME = "com.speechtrans.bridge"
HOST_DIRS = [
    Path.home() / ".config" / "google-chrome" / "NativeMessagingHosts",
    Path.home() / ".config" / "chromium" / "NativeMessagingHosts",
    Path.home() / ".config" / "google-chrome-beta" / "NativeMessagingHosts",
    # Chrome for Testing / Playwright builds use this product name.
    Path.home() / ".config" / "google-chrome-for-testing" / "NativeMessagingHosts",
    Path.home() / ".config" / "microsoft-edge" / "NativeMessagingHosts",
]


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def extension_id(manifest: dict) -> str:
    key = manifest.get("key")
    if not key:
        raise SystemExit("extension/manifest.json has no 'key'; cannot derive a stable ID")
    digest = hashlib.sha256(base64.b64decode(key)).hexdigest()[:32]
    return "".join(chr(ord("a") + int(char, 16)) for char in digest)


def write_wrapper(server_dir: Path) -> Path:
    wrapper = server_dir / "scripts" / "native_host.sh"
    python = server_dir / ".venv" / "bin" / "python"
    if python.is_file():
        exec_line = f'exec "{python}" -m app.native_host'
    else:
        exec_line = f'exec "{shutil.which("uv") or "uv"}" run --project "{server_dir}" python -m app.native_host'
    wrapper.write_text(
        "#!/bin/sh\n"
        "# Generated by scripts/install_native_host.py\n"
        f'export PYTHONPATH="{server_dir}"\n'
        f"{exec_line}\n",
        encoding="utf-8",
    )
    wrapper.chmod(wrapper.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return wrapper


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--uninstall", action="store_true")
    args = parser.parse_args()

    root = repo_root()
    ext_manifest_path = root / "extension" / "manifest.json"
    manifest = json.loads(ext_manifest_path.read_text(encoding="utf-8"))
    ext_id = extension_id(manifest)
    server_dir = root / "server"

    if args.uninstall:
        for directory in HOST_DIRS:
            target = directory / f"{HOST_NAME}.json"
            if target.exists():
                target.unlink()
                print(f"removed {target}")
        wrapper = server_dir / "scripts" / "native_host.sh"
        if wrapper.exists():
            wrapper.unlink()
            print(f"removed {wrapper}")
        return

    wrapper = write_wrapper(server_dir)
    host_manifest = {
        "name": HOST_NAME,
        "description": "SpeechTrans bridge to the local GPU translation server",
        "path": str(wrapper),
        "type": "stdio",
        "allowed_origins": [f"chrome-extension://{ext_id}/"],
    }

    written = 0
    for directory in HOST_DIRS:
        if not directory.parent.exists():
            continue  # browser not installed
        directory.mkdir(parents=True, exist_ok=True)
        target = directory / f"{HOST_NAME}.json"
        target.write_text(json.dumps(host_manifest, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {target}")
        written += 1

    if written == 0:
        fallback = HOST_DIRS[0]
        fallback.mkdir(parents=True, exist_ok=True)
        target = fallback / f"{HOST_NAME}.json"
        target.write_text(json.dumps(host_manifest, indent=2) + "\n", encoding="utf-8")
        print(f"wrote {target} (no existing browser profile found)")

    print(f"wrapper: {wrapper}")
    print(f"extension id: {ext_id}")
    print("\nNext: restart Chrome, then load the extension from ./extension (Load unpacked).")


if __name__ == "__main__":
    main()
